alter table public.site_videos enable row level security;
alter table public.site_settings enable row level security;
alter table public.bookings enable row level security;
alter table public.comments enable row level security;
alter table public.comment_likes enable row level security;
alter table public.comment_replies enable row level security;
alter table public.email_verifications enable row level security;

create policy "Public can read mixtapes"
  on public.mixtapes for select to anon, authenticated using (true);

create policy "Public can read events"
  on public.events for select to anon, authenticated using (true);

create policy "Public can read gallery"
  on public.gallery_items for select to anon, authenticated using (true);

create policy "Public can read videos"
  on public.site_videos for select to anon, authenticated using (true);

create policy "Public can read site settings"
  on public.site_settings for select to anon, authenticated using (true);

create policy "Public can read comments"
  on public.comments for select to anon, authenticated using (true);

create policy "Authenticated users can manage comment likes"
  on public.comment_likes for all to authenticated
  using (user_id = auth.uid()) with check (user_id = auth.uid());

create policy "Public can read comment replies"
  on public.comment_replies for select to anon, authenticated using (true);

create policy "Authenticated users can create comment replies"
  on public.comment_replies for insert to authenticated
  with check (user_id = auth.uid());

create policy "Authenticated users can manage site settings"
  on public.site_settings for all to authenticated using (true) with check (true);

create policy "Authenticated users can manage videos"
  on public.site_videos for all to authenticated using (true) with check (true);

