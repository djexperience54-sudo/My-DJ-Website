create table if not exists public.mixtapes (
  id text primary key,
  genre text not null,
  title text not null,
  artwork text not null,
  description text not null,
  audio_url text,
  created_at timestamptz not null default now()
);

create table if not exists public.events (
  id text primary key,
  month text not null,
  day text not null,
  title text not null,
  details text not null,
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.gallery_items (
  id text primary key,
  src text not null,
  alt text not null,
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.site_videos (
  id text primary key default gen_random_uuid()::text,
  title text not null,
  url text not null,
  type text not null default 'youtube',
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.site_settings (
  id text primary key default 'default',
  hero_title text not null default 'INT''L DJ EXPERIENCE',
  hero_subtitle text not null default 'Live energy. Deep culture. Unforgettable nights.',
